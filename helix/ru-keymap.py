#!/usr/bin/env python3
"""Mirror helix's default normal-mode keymap onto the macOS "Russian" layout.

Every key that types a Cyrillic letter on the Russian layout gets a twin binding for the
same physical key (h -> р, g g -> п п, space f -> space а, ...), so normal mode and its
menus work whichever input source is active. Alt/Ctrl combos are left to WezTerm, which
already sends them by physical key. The result is written into helix/config.toml between
the marker lines; re-run after a helix upgrade, since a renamed command makes helix reject
the whole config.

Usage: python3 helix/ru-keymap.py <default.rs>
  <default.rs> is helix-term/src/keymap/default.rs of the installed helix version:
  gh api -H "Accept: application/vnd.github.raw" \\
    "repos/helix-editor/helix/contents/helix-term/src/keymap/default.rs?ref=$(hx --version | cut -d' ' -f2)"
"""

import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

# US character -> Russian character typed by the same physical key. Keys whose Russian
# character is ASCII too (number row symbols, ` ~ / ?) are left out: binding them would
# shadow helix's own bindings for those characters.
US, RU = "qwertyuiop[]asdfghjkl;'\\zxcvbnm,.", "йцукенгшщзхъфывапролджэёячсмитьбю"
US_SHIFT, RU_SHIFT = 'QWERTYUIOP{}ASDFGHJKL:"|ZXCVBNM<>', "ЙЦУКЕНГШЩЗХЪФЫВАПРОЛДЖЭЁЯЧСМИТЬБЮ"
assert len(US) == len(RU) and len(US_SHIFT) == len(RU_SHIFT)
RU_KEY = dict(zip(US + US_SHIFT, RU + RU_SHIFT))

# Modes whose input is Latin anyway (typed commands, select-mode motions) switch the input
# source to ABC first; macism is installed by install.sh.
SWITCH_TO_ABC = ":run-shell-command ~/.local/bin/macism com.apple.keylayout.ABC"
SWITCHING_COMMANDS = {"command_mode", "select_mode"}

BEGIN = "# >>> Russian layout mirror: generated by ru-keymap.py, don't edit by hand"
END = "# <<< Russian layout mirror"

KEY = r'"(?:[^"\\]|\\.)*"'
KEYS = rf"({KEY}(?:\s*\|\s*{KEY})*)"
BIND = re.compile(rf"^{KEYS}\s*=>\s*(\w+),?$")
MENU = re.compile(rf'^{KEYS}\s*=>\s*\{{\s*"[^"]*"(.*)$')


@dataclass
class Bind:
    keys: list
    command: str


@dataclass
class Menu:
    keys: list
    sticky: bool
    entries: list = field(default_factory=list)


def parse_normal(source):
    """Parse the normal-mode keymap! block of default.rs into Bind/Menu entries."""
    lines = source.split("let normal = keymap!({", 1)[1].splitlines()[1:]
    root = []
    stack = [root]
    for raw in lines:
        line = raw.split("//", 1)[0].strip()
        if not line:
            continue
        if line.startswith("});"):
            break
        if line in ("}", "},"):
            stack.pop()
            continue
        keys = None
        if m := MENU.match(line):
            keys = [json.loads(k) for k in re.findall(KEY, m.group(1))]
            menu = Menu(keys, "sticky=true" in m.group(2))
            stack[-1].append(menu)
            stack.append(menu.entries)
        elif m := BIND.match(line):
            keys = [json.loads(k) for k in re.findall(KEY, m.group(1))]
            stack[-1].append(Bind(keys, m.group(2)))
        else:
            sys.exit(f"unparsed default.rs line: {raw!r}")
    if len(stack) != 1:
        sys.exit("unbalanced menus in default.rs")
    return root


def mirror_tables(entries, path, tables, new_menu):
    """Collect TOML tables for one menu.

    A new menu (one reached by a Cyrillic key) must be defined in full, so it also gets the
    keys that are the same on both layouts (space, arrows, Ctrl combos). A menu that
    already exists in helix's defaults only needs the Cyrillic twins merged into it.
    """
    rows = []
    tables.append((path, rows))
    for entry in entries:
        twins = [RU_KEY[k] for k in entry.keys if k in RU_KEY]
        same = [k for k in entry.keys if k not in RU_KEY]
        if isinstance(entry, Bind):
            command = entry.command
            value = [SWITCH_TO_ABC, command] if command in SWITCHING_COMMANDS else command
            rows.extend((k, value) for k in twins + (same if new_menu else []))
        elif not entry.sticky:  # a menu defined in TOML can't be made sticky
            for k in twins:
                mirror_tables(entry.entries, path + (k,), tables, new_menu=True)
            for k in same:
                mirror_tables(entry.entries, path + (k,), tables, new_menu)


def toml_key(key):
    return key if re.fullmatch(r"[A-Za-z0-9_-]+", key) else json.dumps(key, ensure_ascii=False)


def toml_value(value):
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=False)


def render(tables):
    out = [BEGIN]
    for path, rows in tables:
        if not rows:
            continue
        out.append("")
        out.append("[" + ".".join(toml_key(k) for k in ("keys", "normal") + path) + "]")
        out.extend(f"{toml_key(k)} = {toml_value(v)}" for k, v in rows)
    out.append(END)
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    tables = []
    mirror_tables(parse_normal(Path(sys.argv[1]).read_text()), (), tables, new_menu=False)
    block = render(tables)

    config = Path(__file__).resolve().parent / "config.toml"
    text = config.read_text()
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        text = head + block + rest.split(END + "\n", 1)[1]
    else:
        text = text.rstrip("\n") + "\n\n" + block
    config.write_text(text)


if __name__ == "__main__":
    main()
